create extension if not exists pgcrypto;

create table if not exists public.students (
  id uuid primary key default gen_random_uuid(),
  student_number text not null unique,
  student_name text not null,
  normalized_name text not null,
  status text not null default 'active'
    check (status in ('active', 'blocked')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.student_sessions (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null references public.students(id) on delete cascade,
  token_hash text not null unique,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);

create table if not exists public.teacher_sessions (
  id uuid primary key default gen_random_uuid(),
  token_hash text not null unique,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);

create table if not exists public.teacher_login_state (
  id boolean primary key default true check (id),
  failure_count integer not null default 0,
  locked_until timestamptz,
  updated_at timestamptz not null default now()
);

insert into public.teacher_login_state (id)
values (true)
on conflict (id) do nothing;

create table if not exists public.submissions (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null unique references public.students(id) on delete cascade,
  references_text text not null default '',
  reflection text not null default '',
  status text not null default 'incomplete'
    check (status in ('completed', 'incomplete')),
  visibility text not null default 'public'
    check (visibility in ('public', 'hidden')),
  hidden_reason text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.plants (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null references public.students(id) on delete cascade,
  species_number smallint not null check (species_number between 1 and 5),
  korean_name text not null default '',
  scientific_name text not null default '',
  discovery_date date,
  discovery_place text not null default '',
  habitat text not null default '',
  features text not null default '',
  status text not null default 'incomplete'
    check (status in ('completed', 'incomplete')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (student_id, species_number)
);

create table if not exists public.photos (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null references public.students(id) on delete cascade,
  species_number smallint not null check (species_number between 1 and 5),
  photo_type text not null check (photo_type in ('Leaf', 'Stem', 'Whole')),
  storage_path text not null,
  mime_type text not null default 'image/jpeg',
  size_bytes integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (student_id, species_number, photo_type)
);

create table if not exists public.plant_views (
  id bigint generated by default as identity primary key,
  viewer_student_id uuid not null references public.students(id) on delete cascade,
  target_student_id uuid not null references public.students(id) on delete cascade,
  plant_id uuid not null references public.plants(id) on delete cascade,
  viewed_at timestamptz not null default now()
);

create index if not exists student_sessions_token_idx
  on public.student_sessions(token_hash);
create index if not exists student_sessions_expiry_idx
  on public.student_sessions(expires_at);
create index if not exists teacher_sessions_token_idx
  on public.teacher_sessions(token_hash);
create index if not exists teacher_sessions_expiry_idx
  on public.teacher_sessions(expires_at);
create index if not exists plants_student_idx
  on public.plants(student_id);
create index if not exists photos_student_idx
  on public.photos(student_id);
create index if not exists plant_views_viewed_at_idx
  on public.plant_views(viewed_at desc);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists students_set_updated_at on public.students;
create trigger students_set_updated_at
before update on public.students
for each row execute function public.set_updated_at();

drop trigger if exists submissions_set_updated_at on public.submissions;
create trigger submissions_set_updated_at
before update on public.submissions
for each row execute function public.set_updated_at();

drop trigger if exists plants_set_updated_at on public.plants;
create trigger plants_set_updated_at
before update on public.plants
for each row execute function public.set_updated_at();

drop trigger if exists photos_set_updated_at on public.photos;
create trigger photos_set_updated_at
before update on public.photos
for each row execute function public.set_updated_at();

